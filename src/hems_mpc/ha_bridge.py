"""Home Assistant MQTT Auto-Discovery payloads and YAML Modbus templates for hybrid inverters."""

from __future__ import annotations

import json


def build_mqtt_discovery_payloads(node_id: str = "pl_hems_mpc") -> dict[str, dict]:
    """Return MQTT Auto-Discovery JSON payloads for Home Assistant (`homeassistant/.../config`)."""
    device_block = {
        "identifiers": [node_id],
        "name": "PL-HEMS 15-min MILP Controller",
        "manufacturer": "open-source (pl-hems-mpc)",
        "model": "MPC-MILP + SunSpec Modbus HIL",
        "sw_version": "0.1.0",
    }
    entities = {
        f"homeassistant/sensor/{node_id}/bess_target_power/config": {
            "name": "MPC Battery Power Setpoint",
            "unique_id": f"{node_id}_bess_target_w",
            "state_topic": f"hems/{node_id}/state",
            "value_template": "{{ value_json.bess_target_w }}",
            "unit_of_measurement": "W",
            "device_class": "power",
            "state_class": "measurement",
            "device": device_block,
        },
        f"homeassistant/sensor/{node_id}/export_limit_w/config": {
            "name": "MPC Dynamic Export Limit",
            "unique_id": f"{node_id}_export_limit_w",
            "state_topic": f"hems/{node_id}/state",
            "value_template": "{{ value_json.export_limit_w }}",
            "unit_of_measurement": "W",
            "device_class": "power",
            "device": device_block,
        },
        f"homeassistant/sensor/{node_id}/rce_price/config": {
            "name": "PSE 15-min RCE Price",
            "unique_id": f"{node_id}_rce_pln_mwh",
            "state_topic": f"hems/{node_id}/state",
            "value_template": "{{ value_json.rce_pln_mwh }}",
            "unit_of_measurement": "PLN/MWh",
            "device": device_block,
        },
        f"homeassistant/binary_sensor/{node_id}/zero_export_active/config": {
            "name": "Negative RCE Zero-Export Guard",
            "unique_id": f"{node_id}_zero_export",
            "state_topic": f"hems/{node_id}/state",
            "value_template": "{{ 'ON' if value_json.zero_export else 'OFF' }}",
            "device": device_block,
        },
    }
    return entities


def render_ha_modbus_yaml(host: str = "192.168.1.50", port: int = 502) -> str:
    """Return a ready-to-paste Home Assistant `modbus:` & `automation:` YAML snippet."""
    return f"""# Home Assistant configuration.yaml snippet generated by pl-hems-mpc
modbus:
  - name: hybrid_inverter_ems
    type: tcp
    host: {host}
    port: {port}
    sensors:
      - name: "Inverter Battery SoC"
        address: 40010
        unit_of_measurement: "%"
        scale: 0.1
        precision: 1
        scan_interval: 15
      - name: "Inverter Grid PCC Power"
        address: 40014
        unit_of_measurement: "W"
        data_type: int16
        device_class: power
        scan_interval: 15

automation:
  - id: pl_hems_mpc_15min_dispatch
    alias: "PL-HEMS: Write 15-min MILP Setpoints & Watchdog Heartbeat"
    trigger:
      - platform: time_pattern
        minutes: "/15"
    action:
      - service: modbus.write_register
        data:
          hub: hybrid_inverter_ems
          unit: 1
          address: 40001
          value: >
            {{% set mode = states('sensor.mpc_ems_mode') | int(0) %}}
            {{% set p_cmd = states('sensor.mpc_battery_power_setpoint') | int(0) %}}
            {{% set p_u16 = (p_cmd + 65536) if p_cmd < 0 else p_cmd %}}
            {{% set exp_lim = states('sensor.mpc_dynamic_export_limit') | int(10000) %}}
            {{% set hb = (now().timestamp() // 60) | int % 65535 %}}
            [{{{{ mode }}}}, {{{{ p_u16 }}}}, {{{{ exp_lim }}}}, {{{{ hb }}}}]
"""


def format_state_message(
    bess_target_w: int,
    export_limit_w: int,
    rce_pln_mwh: float,
    sdac_pln_mwh: float,
    soc_pct: float,
) -> str:
    """Serialize the current 15-minute MPC dispatch state as a JSON payload for MQTT topic `hems/pl_hems_mpc/state`."""
    payload = {
        "bess_target_w": int(bess_target_w),
        "export_limit_w": int(export_limit_w),
        "rce_pln_mwh": round(float(rce_pln_mwh), 2),
        "sdac_pln_mwh": round(float(sdac_pln_mwh), 2),
        "soc_pct": round(float(soc_pct), 1),
        "zero_export": bool(rce_pln_mwh <= 0.0),
    }
    return json.dumps(payload)
